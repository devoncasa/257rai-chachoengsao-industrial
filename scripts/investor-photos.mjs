export function investorPhotos(topic, start = 0, end = 4) {
  const photos = captions[topic].slice(start, end).map((caption, i) => {
    const number = start + i + 1;
    return `<figure><img src="/media/investors/${topic}-${number}.webp" width="768" height="512" loading="lazy" decoding="async" alt="${caption}"><figcaption><span aria-hidden="true">0${number}</span> ${caption}</figcaption></figure>`;
  });
  return `<div class="investor-photos investor-photos--${topic} investor-photos--pair-${start}" aria-label="ภาพจำลองประกอบ">${photos.join('')}<p class="photo-credit">ภาพจำลองเพื่ออธิบายแนวคิดการลงทุน · ไม่ใช่ภาพแปลงที่ประกาศขาย</p></div>`;
}
